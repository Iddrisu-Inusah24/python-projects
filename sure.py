# # To-Do List with File Handling
def show_task():
    print("\nTo-Do List Menu")
    print("1. View tasks")
    print("2. Add task")
    print("3. Remove task")
    print("4. Exit")

# Load tasks from file
try:
    with open("tasks.txt", "r") as file:
        tasks = [line.strip() for line in file.readlines()]
except FileNotFoundError:
    tasks = []

def save_tasks():
    with open("tasks.txt", "w") as file:
        for task in tasks:
            file.write(task + "\n")

while True:
    # function call
    show_task()
    # takes user input
    choice = input("Please enter a number from 1-4: ").strip()
    # condtion 1
    if choice == "1":
        if not tasks:
            print("No tasks yet")
        else:
            for i, task in enumerate(tasks, start=1):
                print(f"yor available tasks:   {i}. {task}")
  # condtion 2
    elif choice == "2":
        task = input("Add your task: ").strip()
        if task:
            tasks.append(task)
            save_tasks()
            print(f"Your task '{task}' added")
        else:
            print("Invalid input")
   # condtion 3
    elif choice == "3":
        if not tasks:
            print("No tasks yet")
        else:
            for i, task in enumerate(tasks, start=1):
                print(f"{i}. {task}")
            index = input("Enter task number to remove: ").strip()
            if index.isdigit():
                index = int(index)
                if 1 <= index <= len(tasks):
                    removed = tasks.pop(index - 1)
                    save_tasks()
                    print(f"Your task '{removed}' removed")
                else:
                    print("Invalid task number")
            else:
                print("Invalid input")
    # condtion 4
    elif choice == "4":
        print("Goodbye!!!\n")
        break

    else:
        print("Invalid choice. Please select 1-4.")





                
        